# Soften the bottom edge of the far, mid and near terrain bands: the lower
# part of each band fades out, so the flat fill the renderer draws behind it
# shows through without a straight line. Where the fade starts depends on
# where the band's ridge ends, and is written to src/scene/bandFade.ts so
# the renderer starts its fill there. Safe to run again: a band that already
# fades is left alone. Run make-webp.py afterwards.
#   python3 tools/fade-bands.py
import glob, os, json
import numpy as np
from PIL import Image

root = os.path.join(os.path.dirname(__file__), '..')
art = os.path.join(root, 'public', 'art', 'terrain')
out = {}
for png in sorted(glob.glob(os.path.join(art, '*-*.png'))):
    name = os.path.basename(png)[:-4]
    terrain, band = name.rsplit('-', 1)
    if band not in ('far', 'mid', 'near'):
        continue
    im = Image.open(png).convert('RGBA')
    a = np.array(im).astype(np.float64)
    alpha = a[:, :, 3] / 255.0
    H = alpha.shape[0]
    full = np.where(alpha.mean(axis=1) >= 0.9)[0]
    ridge = full[0] / H if len(full) else 0.6
    # Start a little below the ridge, never above 60% down, never below 88%.
    start = min(0.88, max(0.6, ridge + 0.08))
    out[name] = round(start, 3)
    if alpha[-1].mean() < 0.05:
        continue  # already faded
    y0 = int(start * H)
    for y in range(y0, H):
        t = (y - y0 + 1) / (H - y0)
        k = 1 - t * t  # ease: holds near the start, lets go towards the bottom
        a[y, :, 3] *= k
    Image.fromarray(a.clip(0, 255).astype(np.uint8), 'RGBA').save(png, optimize=True)
    print(f'{name}: fades from {start:.2f}')
ts = os.path.join(root, 'src', 'scene', 'bandFade.ts')
with open(ts, 'w') as f:
    f.write('// Generated by tools/fade-bands.py: where each band starts fading out, as a fraction of its height.\n')
    f.write('export const BAND_FADE: Record<string, number> = ' + json.dumps(out, indent=2).replace('"', "'") + ';\n')
